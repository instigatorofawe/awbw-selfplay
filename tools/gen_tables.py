"""Generate src/core/tables.h from the rules JSON in python/awbw/rules/.

uv run python tools/gen_tables.py          # rewrite the header
uv run python tools/gen_tables.py --check  # fail if it is out of date
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "python"))

from awbw import rules  # noqa: E402

OUT = ROOT / "src" / "core" / "tables.h"
MOVE_NAMES = {"F": "Foot", "B": "Boot", "T": "Tread", "W": "Tire", "A": "Air", "S": "Sea", "L": "Lander", "P": "Pipe"}


def ident(name: str) -> str:
    """'Md.Tank' -> 'MdTank', 'silo_empty' -> 'SiloEmpty', 'APC' -> 'Apc'."""
    parts = re.split(r"[^A-Za-z0-9]+", name)
    return "".join(p[:1].upper() + p[1:].lower() if p.isupper() else p[:1].upper() + p[1:] for p in parts if p)


def array(values, width: int = 0) -> str:
    return "{" + ", ".join(str(v).rjust(width) for v in values) + "}"


def generate() -> str:
    r = rules.load()
    n = len(r.units)
    kinds = r.terrain_kinds
    out: list[str] = []
    w = out.append
    w("// Generated by tools/gen_tables.py from python/awbw/rules/*.json. Do not edit.")
    w("// clang-format off")
    w("#pragma once")
    w("")
    w("#include <cstdint>")
    w("")
    w("namespace awbw {")
    w("")
    w(f"inline constexpr int kNumUnitTypes = {n};")
    w(f"inline constexpr int kNumMoveTypes = {len(rules.MOVE_TYPES)};")
    w(f"inline constexpr int kNumTerrainKinds = {len(kinds)};")
    w(f"inline constexpr int kNumWeathers = {len(rules.WEATHERS)};")
    w(f"inline constexpr int kMaxTerrainId = {max(r.terrain)};")
    w(f"inline constexpr int kMaxCoId = {max(r.cos)};")
    w("// Extra attack and defense % every CO gets while a power is on.")
    w(f"inline constexpr int kPowerBonus = {rules.POWER_BONUS};")
    w("inline constexpr int16_t kNoDamage = -1;")
    w("")
    w("enum UnitType : uint8_t {")
    for u in r.units:
        w(f"  k{ident(u.name)} = {u.index},  // AWBW id {u.id}")
    w("};")
    w("")
    w("enum UnitClass : uint8_t { " + ", ".join(f"k{ident(c)}" for c in rules.UNIT_CLASSES) + " };")
    w("")
    w("// AWBW movement_type codes: " + ", ".join(f"{k}={v}" for k, v in MOVE_NAMES.items()))
    w("enum MoveType : uint8_t { " + ", ".join(f"kMove{MOVE_NAMES[m]}" for m in rules.MOVE_TYPES) + " };")
    w("")
    w("enum TerrainKind : uint8_t { " + ", ".join(f"k{ident(k)}" for k in kinds) + " };")
    w("")
    w("struct UnitSpec {")
    w("  const char* name;")
    w("  int32_t awbw_id;")
    w("  int32_t cost;")
    w("  uint8_t cls, move, move_type, vision, fuel, fuel_per_day, hidden_fuel_per_day, ammo, min_range, max_range;")
    w("  bool capture, supplies, repairs, hides, explodes;")
    w("  uint8_t carry_slots;")
    w("  uint32_t carry_mask;  // bit per UnitType this transport can load")
    w("};")
    w("")
    w("inline constexpr UnitSpec kUnits[kNumUnitTypes] = {")
    for u in r.units:
        mask = sum(1 << i for i in u.carry)
        b = lambda x: "true" if x else "false"  # noqa: E731
        w(
            f'  {{"{u.name}", {u.id}, {u.cost}, k{ident(u.cls)}, {u.move}, kMove{MOVE_NAMES[u.move_type]}, {u.vision}, '
            f"{u.fuel}, {u.fuel_per_day}, {u.hidden_fuel_per_day}, {u.ammo}, {u.min_range}, {u.max_range}, "
            f"{b(u.capture)}, {b(u.supplies)}, {b(u.repairs)}, {b(u.hides)}, {b(u.explodes)}, {u.carry_slots}, "
            f"0x{mask:07x}u}},"
        )
    w("};")
    w("")
    for label, table in (("Primary", r.primary), ("Secondary", r.secondary)):
        what = "the ammo weapon" if label == "Primary" else "the weapon that needs no ammo"
        w(f"// Base damage % with {what}, [attacker][defender]; kNoDamage if it cannot hit.")
        w(f"inline constexpr int16_t k{label}Damage[kNumUnitTypes][kNumUnitTypes] = {{")
        for u, row in zip(r.units, table, strict=True):
            w("  " + array((-1 if v is None else v for v in row), 3) + f",  // {u.name}")
        w("};")
        w("")
    w("struct TerrainSpec {")
    w("  bool valid;")
    w("  uint8_t kind;")
    w("  uint8_t defense;  // terrain stars")
    w("  uint8_t country;  // AWBW country id; 0 = neutral")
    w("};")
    w("")
    w("// Indexed by AWBW terrain id.")
    w("inline constexpr TerrainSpec kTerrain[kMaxTerrainId + 1] = {")
    for tid in range(max(r.terrain) + 1):
        t = r.terrain.get(tid)
        if t is None:
            w(f"  {{false, 0, 0, 0}},  // {tid}")
        else:
            w(f"  {{true, k{ident(t.kind)}, {t.defense}, {t.country or 0}}},  // {tid} {t.name}")
    w("};")
    w("")
    w("// Movement cost [weather][terrain kind][move type]; 0 = impassable.")
    w("inline constexpr uint8_t kMoveCost[kNumWeathers][kNumTerrainKinds][kNumMoveTypes] = {")
    for weather in rules.WEATHERS:
        w(f"  {{  // {weather}")
        for kind in kinds:
            costs = r.move_costs[weather][kind]
            w("    " + array(costs.get(m, 0) for m in rules.MOVE_TYPES) + f",  // {kind}")
        w("  },")
    w("};")
    w("")
    w("// One CO's modifiers in one power state. Excludes kPowerBonus.")
    w("struct CoStateSpec {")
    w("  int16_t atk[kNumUnitTypes];  // attack %")
    w("  int16_t def[kNumUnitTypes];  // defense %")
    w("  int8_t move[kNumUnitTypes];")
    w("  int8_t range[kNumUnitTypes];  // max range, indirect units only")
    w("  int16_t terrain_atk[kNumTerrainKinds];  // by the attacker's terrain")
    w("  uint8_t atk_per_star, star_mult, luck_good, luck_bad, tower_atk, tower_def, def_vs_indirect;")
    w("  uint8_t counter, capture, cost;  // %")
    w("  bool move_cost_one;")
    w("  int16_t income_bonus;  // funds per income property")
    w("  int8_t air_fuel_per_day;")
    w("  uint8_t repair_bonus;  // internal HP")
    w("};")
    w("")
    w("struct CoSpec {")
    w("  bool valid;")
    w("  const char* name;")
    w("  uint8_t cop_stars, scop_stars;  // 0 = no such power")
    w("  CoStateSpec state[3];  // none, COP, SCOP")
    w("};")
    w("")
    w("// Indexed by AWBW CO id.")
    w("inline constexpr CoSpec kCos[kMaxCoId + 1] = {")
    for cid in range(max(r.cos) + 1):
        c = r.cos.get(cid)
        if c is None:
            w(f"  {{false, nullptr, 0, 0, {{}}}},  // {cid}")
            continue
        w(f'  {{true, "{c.name}", {c.cop_stars or 0}, {c.scop_stars or 0}, {{  // {cid}')
        for s in (c.d2d, c.cop, c.scop):
            terrain = array(s.terrain_atk.get(k, 0) for k in kinds)
            w(
                f"    {{{array(s.atk)}, {array(s.defense)}, {array(s.move)}, {array(s.range)}, {terrain}, "
                f"{s.atk_per_star}, {s.star_mult}, {s.luck_good}, {s.luck_bad}, {s.tower_atk}, {s.tower_def}, "
                f"{s.def_vs_indirect}, {s.counter}, {s.capture}, {s.cost}, {'true' if s.move_cost_one else 'false'}, "
                f"{s.income_bonus}, {s.air_fuel_per_day}, {s.repair_bonus}}},"
            )
        w("  }},")
    w("};")
    w("")
    w("}  // namespace awbw")
    w("// clang-format on")
    return "\n".join(out) + "\n"


def main() -> int:
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--check", action="store_true", help="exit 1 if the header is out of date")
    args = p.parse_args()
    text = generate()
    if args.check:
        if not OUT.exists() or OUT.read_text() != text:
            print(f"{OUT.relative_to(ROOT)} is out of date; run: uv run python tools/gen_tables.py", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
